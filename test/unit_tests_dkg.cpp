BOOST_AUTO_TEST_CASE( PolynomialValue ) {
    libBLS::Dkg obj = libBLS::Dkg( 3, 4 );
    std::vector< libBLS::algebra::FrScalar > polynomial = { libBLS::algebra::FrScalar::fromString(
                                                                "1", libBLS::Base::DEC ),
        libBLS::algebra::FrScalar::fromString( "0", libBLS::Base::DEC ),
        libBLS::algebra::FrScalar::fromString( "1", libBLS::Base::DEC ) };

    libBLS::algebra::FrScalar value = obj.PolynomialValue( polynomial, 5 );

    BOOST_REQUIRE( value == libBLS::algebra::FrScalar::fromString( "26", libBLS::Base::DEC ) );

    polynomial.clear();

    polynomial = { libBLS::algebra::FrScalar::fromString( "0", libBLS::Base::DEC ),
        libBLS::algebra::FrScalar::fromString( "1", libBLS::Base::DEC ),
        libBLS::algebra::FrScalar::fromString( "0", libBLS::Base::DEC ) };

    BOOST_REQUIRE_THROW( value = obj.PolynomialValue( polynomial, 5 ), std::logic_error );

    std::vector< libBLS::algebra::FrScalar > shortPol = polynomial;
    shortPol.erase( shortPol.begin() );

    BOOST_REQUIRE_THROW(
        value = obj.PolynomialValue( shortPol, 5 ), libBLS::ThresholdUtils::IncorrectInput );
}

BOOST_AUTO_TEST_CASE( verification ) {
    libBLS::Dkg obj = libBLS::Dkg( 2, 2 );

    auto polynomial_fst = obj.GeneratePolynomial();
    auto polynomial_snd = obj.GeneratePolynomial();

    std::vector< libBLS::algebra::G2Point > verification_vector_fst =
        obj.VerificationVector( polynomial_fst );
    std::vector< libBLS::algebra::G2Point > verification_vector_snd =
        obj.VerificationVector( polynomial_snd );

    libBLS::algebra::FrScalar shared_by_fst_to_snd = obj.SecretKeyContribution( polynomial_snd )[1];
    libBLS::algebra::FrScalar shared_by_snd_to_fst = obj.SecretKeyContribution( polynomial_fst )[0];

    BOOST_REQUIRE( obj.Verification( 0, shared_by_snd_to_fst, verification_vector_fst ) );
    BOOST_REQUIRE( obj.Verification( 1, shared_by_fst_to_snd, verification_vector_snd ) );


    // these lines show that only correctly generated by the algorithm values can be verified
    BOOST_REQUIRE( obj.Verification( 0, shared_by_snd_to_fst + libBLS::algebra::FrScalar::random(),
                       verification_vector_fst ) == false );
    BOOST_REQUIRE( obj.Verification( 1, shared_by_fst_to_snd + libBLS::algebra::FrScalar::random(),
                       verification_vector_snd ) == false );
}

std::default_random_engine rand_gen( ( unsigned int ) time( 0 ) );

BOOST_AUTO_TEST_CASE( PolySize ) {
    for ( size_t i = 0; i < 100; i++ ) {
        size_t num_all = rand_gen() % 16 + 1;
        size_t num_signed = rand_gen() % num_all + 1;
        libBLS::Dkg obj = libBLS::Dkg( num_signed, num_all );
        std::vector< libBLS::algebra::FrScalar > pol = obj.GeneratePolynomial();
        BOOST_REQUIRE( pol.size() == num_signed );
        BOOST_REQUIRE( pol.at( num_signed - 1 ) != libBLS::algebra::FrScalar::zero() );
    }
}

BOOST_AUTO_TEST_CASE( ZeroSecret ) {
    for ( size_t i = 0; i < 100; i++ ) {
        libBLS::Dkg dkg_obj = libBLS::Dkg( 2, 2 );

        libBLS::algebra::FrScalar num1 = libBLS::algebra::FrScalar::random();
        libBLS::algebra::FrScalar num2 = -num1;
        std::vector< libBLS::algebra::FrScalar > pol;
        pol.push_back( num1 );

        BOOST_REQUIRE_THROW(
            dkg_obj.SecretKeyShareCreate( pol ), libBLS::ThresholdUtils::IncorrectInput );

        pol.push_back( num2 );

        BOOST_REQUIRE_THROW( dkg_obj.SecretKeyShareCreate( pol ), std::logic_error );
    }
}

libff::alt_bn128_Fq SpoilCoord( libff::alt_bn128_Fq& sign_coord ) {
    libff::alt_bn128_Fq bad_coord = sign_coord;
    size_t n_bad_bit = rand_gen() % ( bad_coord.size_in_bits() ) + 1;

    mpz_class was_coord;
    bad_coord.as_bigint().to_mpz( was_coord.get_mpz_t() );

    mpz_class mask;
    mpz_set_si( mask.get_mpz_t(), n_bad_bit );

    mpz_class badCoord;
    mpz_xor( badCoord.get_mpz_t(), was_coord.get_mpz_t(), mask.get_mpz_t() );

    bad_coord = libff::alt_bn128_Fq( badCoord.get_mpz_t() );

    return bad_coord;
}

std::vector< libBLS::algebra::G2Point > SpoilVerifVector(
    std::vector< libBLS::algebra::G2Point >& verif_vect ) {
    size_t elem_to_spoil = rand_gen() % verif_vect.size();
    size_t bad_coord_num = rand_gen() % 6;
    std::vector< libBLS::algebra::G2Point > bad_verif_vect = verif_vect;
    switch ( bad_coord_num ) {
    case 0: {
        libBLS::algebra::FqRefWrapper ref_to_elem(
            bad_verif_vect.at( elem_to_spoil ).getXRef().getC0Ref() );
        ref_to_elem.asBackendRef() =
            libBLS::algebra::FqElementTestAccessor::spoil( ref_to_elem.asBackendRef() );
        break;
    }
    case 1: {
        libBLS::algebra::FqRefWrapper ref_to_elem(
            bad_verif_vect.at( elem_to_spoil ).getXRef().getC1Ref() );
        ref_to_elem.asBackendRef() =
            libBLS::algebra::FqElementTestAccessor::spoil( ref_to_elem.asBackendRef() );
        break;
    }
    case 2: {
        libBLS::algebra::FqRefWrapper ref_to_elem(
            bad_verif_vect.at( elem_to_spoil ).getYRef().getC0Ref() );
        ref_to_elem.asBackendRef() =
            libBLS::algebra::FqElementTestAccessor::spoil( ref_to_elem.asBackendRef() );
        break;
    }
    case 3: {
        libBLS::algebra::FqRefWrapper ref_to_elem(
            bad_verif_vect.at( elem_to_spoil ).getYRef().getC1Ref() );
        ref_to_elem.asBackendRef() =
            libBLS::algebra::FqElementTestAccessor::spoil( ref_to_elem.asBackendRef() );
        break;
    }
    case 4: {
        libBLS::algebra::FqRefWrapper ref_to_elem(
            bad_verif_vect.at( elem_to_spoil ).getZRef().getC0Ref() );
        ref_to_elem.asBackendRef() =
            libBLS::algebra::FqElementTestAccessor::spoil( ref_to_elem.asBackendRef() );
        break;
    }
    case 5: {
        libBLS::algebra::FqRefWrapper ref_to_elem(
            bad_verif_vect.at( elem_to_spoil ).getZRef().getC1Ref() );
        ref_to_elem.asBackendRef() =
            libBLS::algebra::FqElementTestAccessor::spoil( ref_to_elem.asBackendRef() );
        break;
    }
    }

    return bad_verif_vect;
}

BOOST_AUTO_TEST_CASE( Verification2 ) {
    for ( size_t i = 0; i < 100; i++ ) {
        size_t num_all = rand_gen() % 16 + 1;
        size_t num_signed = rand_gen() % num_all + 1;
        libBLS::Dkg obj = libBLS::Dkg( num_signed, num_all );
        BOOST_REQUIRE( obj.GetN() == num_all );
        BOOST_REQUIRE( obj.GetT() == num_signed );

        std::vector< libBLS::algebra::FrScalar > pol = obj.GeneratePolynomial();
        std::vector< libBLS::algebra::FrScalar > secret_shares = obj.SecretKeyContribution( pol );
        std::vector< libBLS::algebra::G2Point > verif_vect = obj.VerificationVector( pol );

        std::vector< libBLS::algebra::FrScalar > shortPol = pol;
        shortPol.erase( shortPol.begin() );

        std::vector< libBLS::algebra::G2Point > shortVV = verif_vect;
        shortVV.erase( shortVV.begin() );

        for ( size_t i = 0; i < num_all; i++ ) {
            BOOST_REQUIRE( obj.Verification( i, secret_shares.at( i ), verif_vect ) );

            // // should not be valid mathematical construct for the validation - should be rejected
            BOOST_REQUIRE( !obj.Verification(
                i, secret_shares.at( i ) + libBLS::algebra::FrScalar::one(), verif_vect ) );

            // verification vec should not be well formed
            BOOST_REQUIRE(
                !obj.Verification( i, secret_shares.at( i ), SpoilVerifVector( verif_vect ) ) );

            // // short verification vector should not be valid - throw
            BOOST_REQUIRE_THROW( obj.Verification( i, secret_shares.at( i ), shortVV ),
                libBLS::ThresholdUtils::IncorrectInput );
        }

        BOOST_REQUIRE_THROW(
            obj.VerificationVector( shortPol ), libBLS::ThresholdUtils::IncorrectInput );
    }
}

